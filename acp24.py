# Create two sets
set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}

print("Set 1:", set1)
print("Set 2:", set2)

# Find symmetric difference
result = set1.symmetric_difference(set2)

print("Symmetric Difference:", result)